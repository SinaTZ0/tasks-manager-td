/*===== Activity =====*/
// The history of every change (docs/app.md rule 7), written in the same transaction as the change by `recordActivity`
// (`src/orpc/activity/service.ts`). Append-only: a trigger (drizzle/*_activity-append-only.sql) refuses updates and
// deletes. `taskId` has no foreign key, so an archived task can be hard-deleted and its history stays; `snapshot`
// keeps what the entry needs to read well later (a task's code and title, a column's name), since those change.

export const activity = pgTable(
  "activity",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    /** Null for changes to the team itself (accounts, roles). */
    projectId: uuid("project_id").references(() => project.id, { onDelete: "restrict" }),
    taskId: uuid("task_id"),
    actorId: text("actor_id")
      .notNull()
      .references(() => user.id, { onDelete: "restrict" }),
    /** One of `ACTIVITY_ACTIONS` (`src/orpc/activity/constants.ts`). */
    action: text("action").notNull(),
    before: jsonb("before"),
    after: jsonb("after"),
    snapshot: jsonb("snapshot").notNull().default({}),
    createdAt: timestamp("created_at").notNull().defaultNow(),
  },
  (table) => [
    index("activity_project_id_created_at_idx").on(table.projectId, table.createdAt),
    index("activity_task_id_created_at_idx").on(table.taskId, table.createdAt),
  ],
);

/*===== Deploy Steps =====*/
// The server's record of the deploy steps it ran (`deploy/steps/`, docs/deployment.md → Deploy Steps). Only the deploy
// tool reads and writes it, through psql; the app never does. It lives in the database so that a restored dump rolls
// it back with the data the steps changed. The `_baseline` row marks a ledger started: the steps that existed then
// are `skipped`, since a new server's seed already loads what they would.

export const deployStep = pgTable("deploy_step", {
  /** The step file's name without `.md`, or `_baseline`. */
  name: text("name").primaryKey(),
  /** How many commands the step has. */
  commands: integer("commands").notNull(),
  /** How many of them finished; a rerun starts after these. */
  done: integer("done").notNull().default(0),
  /** Marked done without running, when the ledger was started. */
  skipped: boolean("skipped").notNull().default(false),
  startedAt: timestamp("started_at").notNull().defaultNow(),
  /** Null until every command finished. */
  finishedAt: timestamp("finished_at"),
});
