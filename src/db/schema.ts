/*===== Media =====*/
// One row per uploaded image (docs/backend/media.md). The row's id is the `mediaId` in the storage key, and it is inserted only
// after every variant is in the bucket. Entities point to it with a nullable foreign key (`note.image_media_id`, ...).

export const media = pgTable(
  "media",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    // Plain text instead of a pg enum. Allowed values and their variants live in `src/orpc/media/constants.ts`.
    kind: text("kind").notNull(),
    uploadedBy: text("uploaded_by")
      .notNull()
      .references(() => user.id, { onDelete: "restrict" }),
    /** Of the original after rotation, for the `inside` variants' aspect ratio. */
    width: integer("width").notNull(),
    height: integer("height").notNull(),
    /** Data URI of a 16 px wide WebP, shown blurred while the image loads. */
    placeholder: text("placeholder").notNull(),
    /** Set when an entity starts using it. Null means not used yet; the cleanup deletes it 25 hours after upload. */
    attachedAt: timestamp("attached_at"),
    createdAt: timestamp("created_at").notNull().defaultNow(),
  },
  // Serves the cleanup's "unattached and older than 25 hours" scan (`findOrphanedMediaIds`).
  (table) => [index("media_attached_at_created_at_idx").on(table.attachedAt, table.createdAt)],
);

/*===== Notes =====*/
// Each person's own notebook (`src/orpc/note/`, `src/routes/notes/`): only its owner ever reads a note.

export const note = pgTable(
  "note",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    ownerId: text("owner_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    title: text("title").notNull(),
    body: text("body").notNull().default(""),
    /** Cleared if the media row is ever deleted, so a note never points at a missing image. */
    imageMediaId: uuid("image_media_id").references(() => media.id, { onDelete: "set null" }),
    createdAt: timestamp("created_at").notNull().defaultNow(),
  },
  (table) => [index("note_owner_id_created_at_idx").on(table.ownerId, table.createdAt)],
);

/*===== Projects =====*/
// One board per project (docs/task-manager-plan.md → Decisions). Only an admin creates one and picks its members;
// a member sees only their own projects, an admin every project. Projects are never deleted.

export const project = pgTable("project", {
  id: uuid("id").primaryKey().defaultRandom(),
  name: text("name").notNull(),
  /** The task-code prefix (`TD` in `TD-42`). Never changes, so a code someone wrote down in chat keeps working. */
  key: text("key").notNull().unique(),
  /** The last task number handed out. Raised in the task's insert transaction, so a number is never reused. */
  taskCounter: integer("task_counter").notNull().default(0),
  createdBy: text("created_by")
    .notNull()
    .references(() => user.id, { onDelete: "restrict" }),
  createdAt: timestamp("created_at").notNull().defaultNow(),
});

export const projectMember = pgTable(
  "project_member",
  {
    projectId: uuid("project_id")
      .notNull()
      .references(() => project.id, { onDelete: "cascade" }),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    addedAt: timestamp("added_at").notNull().defaultNow(),
  },
  // The primary key serves "is this user a member of this project"; the index serves "this user's projects".
  (table) => [
    primaryKey({ columns: [table.projectId, table.userId] }),
    index("project_member_user_id_idx").on(table.userId),
  ],
);

/*===== Board Columns =====*/
// Every project has exactly one column of each kind (`COLUMN_KINDS` in `src/orpc/project/constants.ts`), created with
// the project, so "pause → the paused column" always has one answer. Logic looks columns up by kind, never by name.

export const boardColumn = pgTable(
  "board_column",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    projectId: uuid("project_id")
      .notNull()
      .references(() => project.id, { onDelete: "cascade" }),
    kind: text("kind").notNull(),
    /** Null means the kind's own name, in the reader's language. Set when an admin renames the column. */
    name: text("name"),
    /** A reorder rewrites this one row. */
    position: positionKey("position").notNull(),
    wipLimit: integer("wip_limit"),
  },
  (table) => [uniqueIndex("board_column_project_id_kind_idx").on(table.projectId, table.kind)],
);

/*===== Tasks =====*/
// A card on a project's board (docs/app.md → Task). It sits in exactly one column (rule 1) and keeps its number for
// life: `TD-42` is the project's key and this number. Archived tasks leave the board but keep their row and history;
// only an admin hard-deletes one, from the archive (rule 10).

export const task = pgTable(
  "task",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    projectId: uuid("project_id")
      .notNull()
      .references(() => project.id, { onDelete: "restrict" }),
    /** From the project's counter, so `TD-42` is never reused. */
    number: integer("number").notNull(),
    columnId: uuid("column_id")
      .notNull()
      .references(() => boardColumn.id, { onDelete: "restrict" }),
    /** Order within the column. */
    position: positionKey("position").notNull(),
    title: text("title").notNull(),
    /** A Tiptap document (`src/lib/rich-text.ts`); null when empty. */
    description: jsonb("description"),
    /** The description's plain text, for search and the history. */
    descriptionText: text("description_text").notNull().default(""),
    /** One of `TASK_PRIORITIES` (`src/orpc/task/constants.ts`). */
    priority: text("priority").notNull().default("medium"),
    dueDate: date("due_date", { mode: "string" }),
    estimateMinutes: integer("estimate_minutes"),
    /** Responsible for the task. Changed only by the owner or an admin, never by delegation (rule 6). */
    ownerId: text("owner_id")
      .notNull()
      .references(() => user.id, { onDelete: "restrict" }),
    /** Doing the work. */
    assigneeId: text("assignee_id").references(() => user.id, { onDelete: "restrict" }),
    createdBy: text("created_by")
      .notNull()
      .references(() => user.id, { onDelete: "restrict" }),
    createdAt: timestamp("created_at").notNull().defaultNow(),
    updatedAt: timestamp("updated_at")
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
    archivedAt: timestamp("archived_at"),
  },
  (table) => [
    uniqueIndex("task_project_id_number_idx").on(table.projectId, table.number),
    // The board reads a project's live tasks, column by column, in order.
    index("task_column_id_position_idx").on(table.columnId, table.position),
    index("task_project_id_archived_at_idx").on(table.projectId, table.archivedAt),
  ],
);

