/*===== Database Schema =====*/
// Single source of truth for tables, read by Drizzle Kit (`drizzle.config.ts`) and the
// runtime client (`client.server.ts`). Every change ships as a migration: `pnpm db:generate --name <what-changed>`, then
// `pnpm db:migrate` (docs/backend/architecture.md, Database).

/*===== Column Types =====*/
/**
 * A fractional-index position key (`fractional-indexing`). Its digits are ASCII and sort byte-wise, so the column uses
 * the `C` collation: the database's default collation would sort `a` before `B` and scramble the order.
 */
const positionKey = customType<{ data: string }>({ dataType: () => 'text collate "C"' });

/*===== Auth (Better-Auth) =====*/
// Mirrors Better-Auth's core tables. Table and column names must match its model and field
// names (`user`, `emailVerified`, …) because the Drizzle adapter looks them up by key, so keep
// them in sync with `@better-auth/core` when upgrading. IDs are strings generated by Better-Auth.

export const user = pgTable("user", {
  id: text("id").primaryKey(),
  name: text("name").notNull(),
  email: text("email").notNull().unique(),
  emailVerified: boolean("email_verified").notNull().default(false),
  image: text("image"),
  // Plain text instead of pg enums: allowed values live in `src/lib/user-constants.ts`. Never set from the client
  // (`input: false` in `auth.server.ts`).
  role: text("role").notNull().default("user"),
  status: text("status").notNull().default("active"),
  /**
   * Their picture on the profile page (`avatar` kind, docs/backend/media.md); Better-Auth's own `image` stays unused.
   * Cleared if the media row is ever deleted.
   */
  avatarMediaId: uuid("avatar_media_id").references((): AnyPgColumn => media.id, { onDelete: "set null" }),
  createdAt: timestamp("created_at").notNull().defaultNow(),
  updatedAt: timestamp("updated_at")
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date()),
});

