/*===== Notifications =====*/
// An alert for one person about one event (docs/app.md → Notification), in the app only (no e-mail yet). Only its
// person ever reads it. `data` keeps what it needs to read well later: the task's code and title, a note.

export const notification = pgTable(
  "notification",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    /** One of `NOTIFICATION_KINDS` (`src/orpc/notification/constants.ts`). */
    kind: text("kind").notNull(),
    /** Who caused it; null for a due-date reminder, which nobody did. */
    actorId: text("actor_id").references(() => user.id, { onDelete: "restrict" }),
    projectId: uuid("project_id")
      .notNull()
      .references(() => project.id, { onDelete: "cascade" }),
    taskId: uuid("task_id").references(() => task.id, { onDelete: "cascade" }),
    /** For a due-date reminder, the due date it was about: a new date may remind again, the same one never. */
    dueDate: date("due_date", { mode: "string" }),
    data: jsonb("data").notNull().default({}),
    readAt: timestamp("read_at"),
    /** When it was handed to the person's push subscriptions, or claimed to be; null until then (slice 19). */
    pushedAt: timestamp("pushed_at"),
    createdAt: timestamp("created_at").notNull().defaultNow(),
  },
  (table) => [
    index("notification_user_id_created_at_idx").on(table.userId, table.createdAt),
    // Serves the push delivery's "not pushed yet" claim.
    index("notification_unpushed_idx")
      .on(table.userId)
      .where(sql`${table.pushedAt} is null`),
    // Serves the bell's unread count.
    index("notification_unread_idx")
      .on(table.userId)
      .where(sql`${table.readAt} is null`),
    // A due-date reminder goes out once per person, task, kind and due date, however often the bell asks.
    uniqueIndex("notification_due_once_idx")
      .on(table.userId, table.taskId, table.kind, table.dueDate)
      .where(sql`${table.dueDate} is not null`),
  ],
);

